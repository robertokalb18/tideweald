// One-time: splits the compiled v16 stylesheet into its two sources.
//   src/styles/tailwind.css  the Tailwind v4.2.1 output (layers and @property rules), kept verbatim
//   src/styles/game.css      the game's own CSS (everything outside Tailwind's layers), formatted for editing
// Unlayered rules beat layered ones whatever their order, so putting the layers first keeps the cascade.
import { readFileSync, writeFileSync } from 'node:fs';
import { transformSync } from 'esbuild';

const s = readFileSync(process.argv[2] ?? 'public/app.css', 'utf8');
const blocks = [];
let depth = 0, start = 0;
for (let i = 0; i < s.length; i++) {
  const c = s[i];
  if (c === '/' && s[i + 1] === '*') { const e = s.indexOf('*/', i + 2); if (depth === 0) blocks.push(s.slice(start, e + 2)), (start = e + 2); i = e + 1; continue; }
  if (c === '{') depth++;
  else if (c === '}' && --depth === 0) blocks.push(s.slice(start, i + 1)), (start = i + 1);
  else if (c === ';' && depth === 0) blocks.push(s.slice(start, i + 1)), (start = i + 1);
}
const tw = [], game = [];
for (const b of blocks) {
  const t = b.trim();
  if (!t) continue;
  (t.startsWith('@layer') || t.startsWith('@property') || t.startsWith('/*!') ? tw : game).push(t);
}
writeFileSync('src/styles/tailwind.css', '/* Generated by Tailwind CSS v4.2.1 (with the animation and shimmer plugins) for v16; kept verbatim. */\n' + tw.join('\n') + '\n');
const pretty = transformSync(game.join('\n'), { loader: 'css', minify: false, target: 'esnext' }).code;
writeFileSync('src/styles/game.css', '/* Tideweald’s own styles (recovered from the v16.11 build and formatted). Edit here; the build minifies them. */\n' + pretty);
console.log(`tailwind blocks ${tw.length}, game blocks ${game.length}`);
